# ------------------------------------------------------------
#  import ... as ... 是给模块起个短名字。
#  matplotlib.pyplot 这个名字太长，全世界都缩写成 plt，属于约定俗成，别改成别的。
#  （对比：你在 lesson03 里写的是 import mcstat，没起别名，因为 mcstat 本来就短。）
# ------------------------------------------------------------
import matplotlib.pyplot as plt


# ------------------------------------------------------------
# 一、把一个 csv 读成三个列表
# ------------------------------------------------------------
def read_flux_csv(path):
    """读 lesson03 吐出的通量 csv，返回 (z_mid, phi, err) 三个列表。"""

    # 三个空列表。[] 就是「空列表」，后面用 .append() 一个一个往里塞。
    # 为什么这里必须用列表而不是像 mean_se 那样用标量？
    #   —— 因为画图要的是「一整条曲线上所有点」，不是一个统计量。
    #      画图是少数几个真的需要把数据全存下来的场合。
    z_mid = []
    phi   = []
    err   = []

    # with open(...) as f:  ——  打开文件，把它绑到名字 f 上。
    #   "r"              = read，只读模式（"w" 会清空文件，别用错）
    #   encoding="utf-8" = 按 UTF-8 解码；Windows 上不写默认是 GBK，将来会乱码
    #   with 的好处：出了这个缩进块，文件自动关闭，哪怕中间抛异常也会关。
    with open(path, "r", encoding="utf-8") as f:
        # readlines() 把整个文件读成一个【列表】，每个元素是一行字符串，
        # 而且每行结尾还带着换行符 "\n"。
        # 例如 lines[0] 可能是 'k,z_lo,z_hi,z_mid,phi,err,R\n'
        lines = f.readlines()

    # ------------------------------------------------------------
    # ① 跳过表头
    #    csv 的第 0 行是表头（一排列名），不是数据，硬转 float 会当场报错。
    #    lines[a:b] 叫「切片」，取第 a 个到第 b-1 个；
    #    b 省略就一直取到末尾，例如 lines[2:] 是「从第 2 个开始，一直到最后」。
    #    问：数据是从第几个元素开始的？2
    # ------------------------------------------------------------
    for line in lines[1:]:

        # line 现在是一整行字符串，例如 '1,0.000,0.100,0.050,9.5e-01,1.2e-03,0.0013\n'
        #
        # .strip()        去掉这行首尾的空白字符，主要是为了干掉结尾那个 "\n"。
        #                 不去掉的话，最后一列会变成 '0.0013\n'，float() 其实也能吃，
        #                 但留着换行符迟早会在别处咬你一口。
        # .split(",")     按逗号切开，得到一个【字符串列表】：
        #                 ['1', '0.000', '0.100', '0.050', '9.5e-01', '1.2e-03', '0.0013']
        parts = line.strip().split(",")

        # ------------------------------------------------------------
        # ② 取出需要的三列，并转成数
        #
        #    ⚠️ parts 里全是【字符串】。'0.05' 和 0.05 是两个不同的东西：
        #       字符串不能做加减，也不能画图。float(...) 把它转成浮点数。
        #
        #    parts[0] 是第 1 列，parts[1] 是第 2 列 …… 下标从 0 开始数。
        #    对着表头 k,z_lo,z_hi,z_mid,phi,err,R 数一下，
        #    z_mid / phi / err 各自是第几个下标？
        #
        #    .append(x) 是列表的方法，意思是「把 x 加到列表末尾」。
        # ------------------------------------------------------------
        z_mid.append(float(parts[3]))
        phi.append(  float(parts[4]))
        err.append(  float(parts[5]))

    # ------------------------------------------------------------
    # ③ 一条便宜的自检
    #    len(x) 是列表的长度（元素个数）。
    #    想两件事：三个列表之间应该满足什么关系？长度为 0 意味着什么（文件空了？
    #    只有表头？路径打错了？）——都属于「读进来了但其实什么也没读到」。
    #
    #    写不出「这条抓什么」就把它删掉（每课验证上限 5 条的那条纪律）。
    # ------------------------------------------------------------
    assert len(parts)>0, "csv 读取异常：%s" % path

    # return 一次返回三个值，实际上是打包成一个元组。
    # 调用方写 a, b, c = read_flux_csv(...) 就能一次拆开 —— 和 mean_se 一样。
    return z_mid, phi, err


# ------------------------------------------------------------
# 二、画
# ------------------------------------------------------------
#  CASES 是一个【列表】，里面每个元素是一个【元组】(文件名, 图例文字)。
#  这样写的好处：以后加第四个 case，只要在这里多加一行，下面的循环一个字不用改。
#
#  ⚠️ 字符串里的 "\\Sigma_t" ：
#     $...$ 之间是数学模式（LaTeX 语法），$\Sigma_t$ 渲染出来就是 Σt。
#     但 "\S" 在 Python 字符串里是转义序列的开头，所以要写两个反斜杠 "\\S"
#     才表示「一个真正的反斜杠」。（另一种写法是在引号前加 r，即 r"$\Sigma_t$"。）
# ------------------------------------------------------------
CASES = [
    ("flux_case1.csv", "case 1: d=2.0, $\\Sigma_t$=1.0, $\\Sigma_s$=0.0"),
    ("flux_case2.csv", "case 2: d=2.0, $\\Sigma_t$=1.0, $\\Sigma_s$=0.8"),
    ("flux_case3.csv", "case 3: d=5.0, $\\Sigma_t$=1.0, $\\Sigma_s$=0.9"),
]

# 坑③ 的验法开关：临时改成 100.0 跑一次，看误差棒是不是明显变大了，然后改回 1.0。
# 「没见过它长出来的误差棒，不算画上了。」
ERR_SCALE = 1.0

# ------------------------------------------------------------
#  plt.subplots() 一次给你两个东西：
#    fig = Figure，整张画布（最后存成 png 的就是它）
#    ax  = Axes，一套坐标系（x 轴 y 轴，以及画在里面的所有东西）
#  figsize=(宽, 高)，单位是英寸。7×5 大约是一张常规论文插图。
#
#  为什么不用网上常见的 plt.plot() / plt.xlabel()？
#    那套接口偷偷操作「当前那张图」，画一张图时没区别，
#    但第 9 课要画双子图（对拍曲线 + 残差）时会立刻乱套。
#    ax 这套从一开始就说清楚「画在哪个坐标系里」。
# ------------------------------------------------------------
fig, ax = plt.subplots(figsize=(7, 5))

# for 一次从 CASES 里取一个元组，并【当场拆成两个变量】path 和 label。
# 这叫元组解包，和 a, b, c = mean_se(...) 是同一件事。
for path, label in CASES:

    z, phi, err = read_flux_csv(path)

    # ------------------------------------------------------------
    # ④ 画一条带误差棒的曲线
    #
    #    ax.errorbar(x, y, yerr=..., label=..., ...) 
    #      前两个是位置参数：x 坐标列表、y 坐标列表
    #      后面都是关键字参数，写不写、什么顺序都行
    #
    #    必须给的：yerr=（误差棒半长，记得乘 ERR_SCALE）、label=（图例文字，用上面的 label）
    #    建议给的：marker="o", markersize=3, capsize=2, linewidth=1
    #              参数含义见讲义第 2 节的表
    #
    #    ⚠️ yerr 要乘 ERR_SCALE，而 err 是个列表，列表不能直接乘浮点数
    #       （[1,2]*2 得到的是 [1,2,1,2]，不是你要的意思！）。
    #       要逐个元素乘，写法是列表推导式：[e * ERR_SCALE for e in err]
    #       读法：「对 err 里的每一个 e，算出 e*ERR_SCALE，组成新列表」。
    #       这是你第一次用列表推导式，记一下这个形状。
    # ------------------------------------------------------------
    ax.errorbar(x=z,y=phi,yerr=[e * ERR_SCALE for e in err] ,label=label,marker="o", markersize=3, capsize=2, linewidth=1)

# ------------------------------------------------------------
# ⑤ 两个轴的标签
#    set_xlabel / set_ylabel 各收一个字符串。
#    要求：必须写清「这个轴是什么量 + 单位」。
#      x 轴是深度，单位厘米
#      y 轴是通量，单位是每平方厘米每个源中子（讲义里给了 LaTeX 写法）
#    ⚠️ 全部用英文 —— 中文在默认字体下会变成一排方块（讲义坑②）。
# ------------------------------------------------------------
ax.set_xlabel("depth (cm)")
ax.set_ylabel("flux (cm$^{-2}$ per source neutron)")
ax.set_title("Track-length flux in a 1D slab (N=1e6, seed=2026)")

# legend() 会自动收集上面所有带 label= 的曲线，生成图例。
# 如果图例是空的，说明你 ④ 里的 label= 没给。
ax.legend()

# grid 画淡网格；alpha 是透明度，0=全透明看不见，1=不透明。
ax.grid(True, alpha=0.3)
# y 用对数轴：case1 是纯吸收，通量按 exp(-Σt·z) 衰减，在半对数坐标上必须是一条直线。
# ⚠️ set_yscale("log") 是以 10 为底，所以图上量出来的斜率是 -Σt*log10(e) = -0.434，不是 -Σt。
ax.set_yscale("log")

# ------------------------------------------------------------
# ⑥ 存图 和 看图，两行
#
#    存：fig.savefig("lesson03_flux.png", dpi=150, bbox_inches="tight")
#        dpi=150            每英寸 150 个像素，7 英寸宽就是 1050 像素，够清楚
#        bbox_inches="tight" 裁掉四周多余白边，不加的话轴标签常被切掉半截
#
#    看：plt.show()
#
#    ⚠️ 这两行的【顺序】是本课最经典的坑（讲义第 3 节坑①）。
#       想一想：show() 弹出窗口、你关掉它之后，那块画布还在不在？
#       顺序错了你会得到一张全白的 png，而且程序不报任何错。
# ------------------------------------------------------------
fig.savefig("lesson03_flux.png", dpi=150, bbox_inches="tight")
plt.show()


