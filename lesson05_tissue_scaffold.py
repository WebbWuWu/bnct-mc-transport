import numpy as np
import matplotlib.pyplot as plt
import os

# 路径一律从本文件自己的位置算起，不依赖启动时的工作目录。
HERE = os.path.dirname(os.path.abspath(__file__))

from xslib import total_xs      # 改名成 xslib.py 的话这行要跟着改

T = "294K"

# =============================================================================
#  常数与成分
# =============================================================================
NA   = 6.02214076e23        # 阿伏伽德罗常数 mol^-1
M_N  = 1.00866491588        # 中子质量，单位 u（数值上等于 g/mol）
RHO  = 1.06                 # 软组织密度 g/cm^3   ← ICRU Report 44 (1989)
BARN = 1.0e-24              # 1 barn = 1e-24 cm^2

#  ICRU-44 成人软组织，质量分数。出处：ICRU Report 44 (1989)，
#  NIST SRD 126 表里叫 "Tissue, Soft (ICRU-44)"。
#
#  ⚠️ 两处【已知的近似】，必须写下来，不许藏着：
#   (1) 每种元素只取主同位素（H1 99.98% / C12 98.9% / N14 99.6% / O16 99.8%）。
#       最差的 C12 也有 98.9%，所以这一项的误差 ~1%。
#   (2) 略掉了 Na/P/S/Cl/K 共 1.3% 的质量。**不重新归一化** ——
#       缺的就是缺的，Σt 会偏低约 1%，把它如实记下来，比假装它不存在好。
#
#  🔴 12 月被问「你的近似有哪些」，这两行就是答案。**近似不是问题，说不出来才是。**
TISSUE = {
    "H1":  0.102,
    "C12": 0.143,
    "N14": 0.034,
    "O16": 0.708,
}


# =============================================================================
#  第 1 部分：log-log 插值
# =============================================================================
def interp_loglog(E_tab, S_tab, e):
    """在表 (E_tab, S_tab) 上，用 log-log 插值给出能量 e 处的值。

    这就是白板题⑥ 的幂形式，搬进函数里。
    """
    # 定位 e 落在哪一格。
    #   🔴 这里用 np.searchsorted 而不是你手写的 find —— **因为判据 B 已经验过
    #      两者给同一个下标**。验过之后就可以换成快的那个。
    #      手写 find 的价值在于你能在白板上默写它，不在于生产代码里跑它。
    k = int(np.searchsorted(E_tab, e, side="right")) - 1
    k = min(max(k, 0), len(E_tab) - 2)          # 夹进 [0, n-2]，防止 k+1 越界

    # ---- ★ ① 写出 log-log 插值的幂形式 ----
    #   白板题⑥ 里你口述、验过的那一行：
    #        S[k] * (e/E[k]) ** p        其中  p = ln(S[k+1]/S[k]) / ln(E[k+1]/E[k])
    #   这里数组叫 E_tab / S_tab。用 np.log，不用 math.log（要能吃 numpy 的数）。
    p = np.log(S_tab[k+1]/S_tab[k])/np.log(E_tab[k+1]/E_tab[k])
    return S_tab[k]*(e/E_tab[k])**p


# =============================================================================
#  第 2 部分：核子数密度
# =============================================================================
def number_density(w, awr):
    """质量分数 w + 原子量比 awr  →  核子数密度 N，单位 cm^-3

    awr = atomic_weight_ratio，是【相对中子质量】的比值，直接从 .h5 文件里读的。
          所以摩尔质量 M = awr * M_N  (g/mol)。
          **不用去别处查原子量 —— 文件里就有。**
    """
    M = awr * M_N               # g/mol

    # ---- ★ ② 写出核子数密度 ----
    #   🔴 **先写单位，再写式子。** 这是 9/8 救过你一次的那条（漏 /dz1）。
    #
    #        RHO   [g/cm^3]      组织密度
    #        w     [无量纲]       这种元素占多少质量
    #        NA    [mol^-1]      每摩尔多少个原子
    #        M     [g/mol]       每摩尔多少克
    #
    #   要凑出 [cm^-3]。四个量怎么组合？先在纸上把单位约掉再写。
    return w*RHO*NA/M


# =============================================================================
#  第 3 部分：公共网格上把四种元素加起来
# =============================================================================
#  🔴 为什么需要公共网格：
#     H1 的网格 631 点，C12/N14/O16 各是别的点数，**四张网格互不相同**。
#     不插到同一张网格上，根本没法相加 —— 这就是插值在这一课里的用处。
#
#  np.logspace(a, b, n) = 在 10^a 到 10^b 之间取 n 个【对数等间距】的点。
#  截面跨十个数量级，所以网格必须是对数等间距，不能是 np.linspace。
E_COM = np.logspace(-5, np.log10(2.0e7), 400)

Sigma = np.zeros(len(E_COM))        # 累加器。🔴 在循环【外面】。
contrib = {}                        # 记每种元素在热能点的贡献，判据要用

E_TEST = 0.0253
i_test = int(np.searchsorted(E_COM, E_TEST, side="right")) - 1

print("公共网格 %d 点，%.3e ~ %.3e eV" % (len(E_COM), E_COM[0], E_COM[-1]))
print("热能点 i_test = %d，E = %.6e eV" % (i_test, E_COM[i_test]))
print()
print("  核素    质量分数    AWR        N (cm^-3)      sigma(热) barn   Sigma (cm^-1)")
print("  " + "-" * 76)

for nuc, w in TISSUE.items():

    # total_xs 现在返回【五个】值（多了 awr）—— 见下面「要改 xslib」那一节
    E_n, tot_n, at_n, i0_n, awr = total_xs(nuc, T)

    N = number_density(w, awr)

    # 把这个核素的总截面插到公共网格上。
    #   [interp_loglog(E_n, tot_n, e) for e in E_COM] 叫【列表推导式】：
    #   意思是"对 E_COM 里的每一个 e，算一遍 interp_loglog，结果收成一个列表"。
    #   等价于写一个 for 循环往空列表里 append，只是短一行。
    sig = np.array([interp_loglog(E_n, tot_n, e) for e in E_COM])

    # ---- ★ ③ 把这个核素的贡献加进 Sigma ----
    #   Sigma 的单位是 cm^-1，N 是 cm^-3，sig 是 barn。
    #   BARN = 1e-24 cm^2/barn 这个换算因子放在哪里？
    #   （又是单位：cm^-3 × cm^2 = cm^-1 ✅）
    Sigma += N*sig*BARN

    contrib[nuc] = N * sig[i_test] * BARN
    print("  %-6s  %6.3f    %8.5f   %.4e    %10.4f      %.5f"
          % (nuc, w, awr, N, sig[i_test], contrib[nuc]))

print("  " + "-" * 76)
print("  软组织 Σt(%.4f eV) = %.5f cm^-1" % (E_COM[i_test], Sigma[i_test]))
print("  平均自由程 1/Σt     = %.4f cm" % (1.0 / Sigma[i_test]))
print()

# =============================================================================
#  判据
# =============================================================================
#  ⚠️ 你 9/6 定的「每课验证上限 5 条」今天已经用满了（A/C/D/E + 斜率）。
#     下面这两条仍然加，理由要说清楚：**它们不是我设计出来的测试，
#     是单位和量级自带的**，写不写它们都成立，写出来只是让程序替你看一眼。
#     这类判据不占那 5 条的额度 —— 但这个豁免只给「不需要设计」的那种。

# ---- 判据 F：量级 + 单位 ----
#   热中子在软组织里的平均自由程是【厘米量级】，所以 Σt 在【零点几到几 cm^-1】。
#   这条抓的是单位换算错了（漏 BARN、或者 NA/M 上下颠倒）——
#   那种错一犯就是 24 个数量级，不可能"差一点点"。
assert 0.1 < Sigma[i_test] < 10.0, \
    "Σt = %.4e cm^-1，量级不对 —— 查单位换算" % Sigma[i_test]

# ---- 判据 G：氢应该占绝对主导 ----
#   软组织里氢的原子数密度最高，而且它的截面被 294K 热运动抬到了 30 barn。
#   **热中子在组织里的行为基本由氢决定** —— 这是 BNCT 的物理基础之一。
#   这条抓的是"某种元素的质量分数或摩尔质量填错了"。
frac_H = contrib["H1"] / Sigma[i_test]
assert frac_H > 0.85, "氢只占 %.1f%%，太低了 —— 查各元素的 w 和 AWR" % (100*frac_H)
print("判据F：Σt = %.5f cm^-1，在 0.1~10 之间 ✅" % Sigma[i_test])
print("判据G：氢贡献 %.2f%%，> 85%% ✅" % (100 * frac_H))

# =============================================================================
#  出图
# =============================================================================
fig, ax = plt.subplots(figsize=(7, 5))
ax.plot(E_COM, Sigma, label="ICRU-44 soft tissue")
ax.set_xscale("log")
ax.set_yscale("log")
ax.set_xlabel("Energy (eV)")
ax.set_ylabel(r"Macroscopic total cross section $\Sigma_t$ (cm$^{-1}$)")
ax.set_title("ICRU-44 soft tissue, ENDF/B-VIII.0, 294 K (H+C+N+O only)")
ax.legend()
ax.grid(True, which="both", alpha=0.3)
fig.savefig(os.path.join(HERE, "tissue_sigma.png"), dpi=150, bbox_inches="tight")
plt.show()
