#
# 🔴 填空前先跑一遍 sorted_key_first_look.py，那里面没有空。
#
# ------------------------------------------------------------
# 它是什么
# ------------------------------------------------------------
#   和 sample_reaction_bisect.py 【算同一件事】，走【两条独立的路】。
#   两条路算出同一个 k，才是一条有分辨率的判据（9/7 立的那条）。
#
#   这一版是主力（9/16 实测平均读表 1.1 次 vs 二分 274.8 次）。
#   二分版是参考实现，只用来对拍，永远不进热路径。
#
# ------------------------------------------------------------
# ⚠️ 签名：这里有一个【你还没决定】的东西
# ------------------------------------------------------------
#   下面写的是 sample_reaction(sigma, total, xi)，order 在函数【里面】算。
#   这样写的唯一理由是：和二分版签名一致，对拍好写。
#
#   🔴 但你今天要回答的那个问题会改掉这个签名：
#      「那个排序顺序从哪来？多久算一次？」
#      如果答案是"外面预先算好、传进来"，签名就变成
#          sample_reaction(sigma, total, xi, order)
#      而函数体里【空 1 那一行直接删掉】，别的一行不改。
#
#   我没有替你决定。先按现在这个填，决定之后改一行。
#
# ------------------------------------------------------------
# 接口约定（和二分版逐字相同）
# ------------------------------------------------------------
#   sigma : 各反应道截面，允许含 0（阈值反应在热能点就是 0）
#   total : 总截面，从外面传进来（省一次求和，代价是可能对不上，见判据 2）
#   xi    : 一个 [0,1) 的随机数。随机性由调用方负责（9/16 纪律）
#   返回  : 【原始下标】k
# ============================================================


def sample_reaction(sigma, total, xi):
    """按 sigma[k]/total 的占比抽一个反应道，返回原始下标 k。
    做法：把下标按 sigma 从大到小排队，然后从大的那头累加着扫。
    """

    n = len(sigma)

    # ---- 判据 1 / 2 / 3：和二分版【逐字相同】，已填好，不要动 ----
    assert total > 0, "total 必须为正，实际是 %r" % total
    assert abs(sum(sigma) / total - 1) < 1e-12, \
        "sigma 与 total 对不上：sum(sigma)=%.17g  total=%.17g  比值=%.17g" \
        % (sum(sigma), total, sum(sigma) / total)
    assert 0 <= xi < 1, "xi 越界或是 nan: %r" % xi

    # ------------------------------------------------------------
    # 空 1：算出 order —— 原始下标按 sigma 从大到小排成的队
    # ------------------------------------------------------------
    #   跑过 sorted_key_first_look.py 的话这一行你已经见过了，两种写法都行。
    #   ⚠️ 排完序 sigma 本身一个字不动，别去改 sigma。
    order = sorted(range(n),key=lambda i: sigma[i],reverse=True)

    # ------------------------------------------------------------
    # 空 2：线性扫描
    # ------------------------------------------------------------
    #   acc 是"扫到目前为止累加的截面"。
    #   扫到第 rank 名、把 sigma[k] 加进 acc 之后，
    #   已经覆盖的占比是 acc / total。
    #
    #   问自己：xi 落在哪个条件下，就该返回这个 k？
    #
    #   🔴 三件事在这一行里同时被决定，想清楚再写：
    #     (a) 比较符号写 < 还是 <=。
    #         random() 返回 [0,1)，左闭右开（9/6 已核对）——
    #         这和 9/16 白板题⑦(3b) 是同一个问题。
    #     (b) 零截面道。排完序 0 全在末尾。
    #         二分版靠不变量【结构上】不可能返回零道；
    #         这一版没有那个保护，9/16 原话：「只能靠把 < 写对」。
    #         写完自己验一次：sigma=[3,0,7] 时，1 号道有没有可能被返回？
    #     (c) 除法。写 acc / total 还是 xi * total？
    #         两者数学上等价，浮点上不一定。第 13 课每秒上亿次，除法是有单价的。

    acc = 0.0
    for rank in range(n):
        k = order[rank]            # 已填：rank 是排名，k 是原始下标
        acc += sigma[k]
        if xi<=acc/total:                   # 空 2
            return k

    # ------------------------------------------------------------
    # 空 3：扫完了一次都没返回，走到了这里
    # ------------------------------------------------------------
    #   先想清楚：【什么情况下会走到这一行？】
    #   提示：xi < 1 是被判据 3 保证了的，而扫完之后 acc/total 应该是 1。
    #        那它为什么可能还没返回？
    #        （答案和 9/9「容差：量级在变的东西要用相对的」是同一件事）
    #
    #   然后决定这里放什么。两种做法，代价不同，选一个并写下理由：
    #     甲：返回某个下标（返回哪个？为什么是它？）
    #     乙：assert 当场炸（炸了之后你拿什么信息去查？）
    #
    #   🔴 判据由 Claude 写（2026-09-18 起的分工）。下面是替换你那条的版本，
    #      连同你那条的三个问题一起说清楚 ——
    #
    #      你写的是：  assert abs(acc/total-1) < 1e-6, "acc越界"
    #
    #      ① 🔴 它通过之后，函数走到底，Python 默认 return None。
    #         9/9 白板题⑤「验证 1 打印出一片 None」是同一个形态：
    #         分支里只做了事，没有 return。
    #      ② 🔴 两边同源。acc 是 sigma 累加出来的，而判据 2 已经钉死了
    #         abs(sum(sigma)/total - 1) < 1e-12。你这条检的是判据 2 检过的东西，
    #         容差还松了 6 个数量级。恒真 assert，第八次。
    #      ③ 消息「acc越界」指向了错误的原因：走到这里不是 acc 越界，是 xi 比
    #         最后那个累积占比还大。而且一个数都没带（9/9：消息要带够查的信息）。
    #
    #   ---- 替换版 ----
    #   什么情况会走到这里：acc 是把 sigma 按【order 的顺序】加出来的，
    #   total 是按【原序】加出来的。两个求和顺序的浮点残差，会让 acc/total
    #   差一点点不到 1，而 xi 恰好掉进那条缝里。
    #   实测：扫 39.9 万组随机 sigma，8.8 万组存在这条缝，最大 3.33e-16。
    #   ⚠️ 但本项目的 LCG 返回 k/2**32，最大 xi ≈ 1-2.3e-10，够不到 1e-16 那条缝，
    #      所以这条路在当前 RNG 下走不到。换 numpy 的 64 位 rng 就走得到。
    #      「它现在不响」和「它是坏的」是两回事。
    #
    #   这条抓什么：抓「扫完没返回，而缺口大得不像浮点残差」。
    #   两边来自两条路：acc（按 order 求和） vs 1（判据 2 在原序上钉死的）。
    assert 1.0 - acc / total < 1e-12, \
        "扫完未返回，且缺口远大于浮点残差：xi=%.17g  acc=%.17g  total=%.17g  缺口=%.3g" \
        % (xi, acc, total, 1.0 - acc / total)

    # 落在那条缝里时，xi 属于最后一个【非零】道的区间尾巴。
    # （这一行是补上那个缺失的 return —— 属于代码不属于判据，但不补的话
    #   函数会返回 None，判据再对也没用。你重写时按你自己的想法改。）
    for r in range(n - 1, -1, -1):
        if sigma[order[r]] > 0:
            return order[r]
    assert False, "sigma 全为零而 total>0，不可能：total=%.17g" % total


# ============================================================
#  对拍：两条独立的路算同一个 k
#  —— 循环和随机数据是搬运，【判据那一行是空 4，你填】
# ============================================================
if __name__ == "__main__":

    import random
    from sample_reaction_bisect import sample_reaction_bisect

    rng = random.Random(20260918)

    n_groups = 300          # 9/16 原值
    n_draws = 200           # 每组抽多少次
    mismatch = 0
    zero_hit = 0
    total_draws = 0

    for g in range(n_groups):
        n = rng.randint(2, 60)

        # 故意塞大量 0（阈值反应在热能点就是 0，这是常态不是脏数据）
        sigma = []
        for i in range(n):
            if rng.random() < 0.5:
                sigma.append(0.0)
            else:
                sigma.append(rng.random() * 10.0 ** rng.randint(-4, 4))

        if sum(sigma) <= 0:      # 全 0 的组跳过，total>0 是判据 1 的前提
            continue
        tot = sum(sigma)

        # 🔴 两版必须用【同一个 order】切 [0,1)，否则它们不在比同一个量。
        #    见下面「空 4」那段说明。
        order = sorted(range(n), key=lambda i: sigma[i], reverse=True)
        sig_sorted = [sigma[i] for i in order]

        for d in range(n_draws):
            xi = rng.random()
            total_draws += 1

            k_lin = sample_reaction(sigma, tot, xi)
            k_bis = order[sample_reaction_bisect(sig_sorted, tot, xi)]

            # ---- 空 4：主判据（2026-09-18，Claude 写）----
            #
            #   你写的是：  assert k_lin == k_bis, "线性扫描与对数扫描结果对不上"
            #
            #   🔴 它必然失败。实测 59600 次里 23396 次不一致（39.3%），
            #      而两个实现【都是对的】。
            #      真因：二分版按【原始顺序】切 [0,1)，本版按【排序后顺序】切。
            #        sigma=[3,0,7] 时 ——
            #            二分：道0 拿 [0,0.3)，道2 拿 [0.3,1)
            #            本版：道2 拿 [0,0.7)，道0 拿 [0.7,1)
            #      两版【分布上等价】（各抽 20 万次都给 [0.300, 0.000, 0.700]），
            #      【逐点不等价】。
            #      ==> 修法：给二分版喂排序后的 sigma，再把排名映射回原始下标。
            #          改完实测 59600 次不一致 0 次。
            #
            #   ⚠️ 这条规格是 Claude 上午给错的，不是你填错的。教训记在这里：
            #      🔴 判据的两边不但要【独立】，还必须先确认它们在【比同一个量】。
            #         （9/7「一条 assert 要有两个独立算出来的量」缺的那一半。）
            #
            #   另外两条是你的：
            #      · 消息里一个值都没有（9/9：assert 的消息必须带够查的信息）。
            #        刚才它响的时候，我们从消息里什么也拿不到，只能另写脚本去查。
            #      · 「对数扫描」是错术语，二分是 binary search / 二分查找。
            #        白板上说错这个词老师会当场停下来（同 9/17「散裂 vs 裂变」）。
            #
            #   这条抓什么：抓两条独立实现算出的道号不一致。
            #   两边来自两条路：排序后线性扫描  vs  二分（每次现算累积占比）。
            if k_lin != k_bis:
                mismatch += 1
                if mismatch <= 3:
                    print("   不一致 #%d: n=%d xi=%.17g  k_lin=%d(sigma=%.6g)  "
                          "k_bis=%d(sigma=%.6g)  total=%.6g"
                          % (mismatch, n, xi, k_lin, sigma[k_lin],
                             k_bis, sigma[k_bis], tot))

            if sigma[k_lin] == 0.0:
                zero_hit += 1

    print("对拍完成")
    print("   组数        : %d" % n_groups)
    print("   抽样次数    : %d" % total_draws)
    print("   不一致      : %d 次" % mismatch)
    print("   返回零截面道: %d 次" % zero_hit)

    # 🔴 判据摆在统计打印【之后】：先看清全貌，再判定。
    #    原来那版是「第一次不一致就 assert 炸」，于是 mismatch 这个计数器永远是 0
    #    —— 一行永远打印 0 的日志。这是 Claude 脚手架自己的锅，也正是 9/9 那条：
    #    「一条判据如果不判定，它就不是判据，是一行日志。」
    assert mismatch == 0, "两版不一致 %d / %d 次" % (mismatch, total_draws)
    assert zero_hit == 0, "返回了零截面道 %d 次" % zero_hit
    print("   -> 两条判据全过")
