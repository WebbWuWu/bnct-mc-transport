import os
import h5py
import numpy as np

LIB    = r"E:\BNCT_GPU\lib80x_hdf5"
NUC    = "B10"
T      = "294K"
E_TEST = 0.0253


def total_xs(nuc, T):
    """读一个核素的截面库，把总截面加出来。

    返回两个东西：
        E     能量网格          长度 n
        total 总截面（barn）     长度 n，和 E 一一对应

    为什么写成函数而不是一路平铺下来：
        因为一会儿 H1 也要算，第 6 节软组织里九种元素每种都要算一遍。
        「调用方负责攒，函数负责算」—— 这是你 9/8 自己写下的那句话。
    """
    path = os.path.join(LIB, nuc + ".h5")
    assert os.path.exists(path), "文件不在这里：%s" % path

    with h5py.File(path, "r") as f:
        root  = f[nuc]
        E     = root["energy"][T][:]
        awr = float(root.attrs["atomic_weight_ratio"])
        names = list(root["reactions"].keys())

        # ---------------------------------------------------------------
        #  🔴 初始化在循环【外面】
        # ---------------------------------------------------------------
        #  total 是一个"累加器"：58 圈往同一个数组上加。
        #  如果写进循环里，每圈都会被清成全 0 —— 跑完只剩最后一个道的截面，
        #  而且**不会报错**，你会得到一条安静的、错的曲线。
        #
        #  这是同一个岔路口的第四次：9/4 v_sum、9/5 r50_sum、9/7 lo/hi。
        #  纪律（你自己写的）：写下 for 之后第一句话 ——
        #      「哪些事只该做一次？那些事在循环外面。」
        # ---------------------------------------------------------------
        total = np.zeros(len(E))

        # dict（字典）—— 第 5 课清单上的新东西，这里第一次用。
        #   {} 是一个空 dict。存：at_i0[钥匙] = 值。取：at_i0[钥匙]
        #   这里钥匙是 MT 号（整数），值是那个道在 i0 处的截面。
        #   ⚠️ 钥匙不一定是字符串！这里就是整数。中括号里加不加引号，看钥匙本身是什么。
        at_i0 = {}

        # 热能点的下标（和第 1 步同一套写法）
        i0 = int(np.searchsorted(E, E_TEST, side="right")) - 1

        n_add = 0                       # 真正加进去了几个道

        for name in sorted(names):
            rx = root["reactions"][name]

            mt        = rx.attrs["mt"]
            redundant = rx.attrs["redundant"]

            xs_ds = rx[T]["xs"]
            thr   = int(xs_ds.attrs["threshold_idx"])
            xs    = xs_ds[:]

            # ---- 判据 A：xs + 阈值偏移，必须正好铺满能量网格 ----
            #   抓「我以为所有道共用一张网格」
            assert len(xs) + thr == len(E), \
                "%s: len(xs)=%d, thr=%d, len(E)=%d —— 对不上" \
                % (name, len(xs), thr, len(E))

            # 记下每个道在 i0 处的值。**冗余道也记** —— 判据 C 要用 MT=107。
            at_i0[int(mt)] = 0.0 if i0 < thr else xs[i0 - thr]

            if redundant:
                continue                # 冗余道：它是别人的和，跳过

            # ---- 判据 E：没有哪个【要加的】道能有 1e6 barn 以上 ----
            #   抓「万一 redundant 标志没打对，把 MT=301/444 这种非截面加了进来」
            #
            #   🔴 这条 assert 的【位置】是有讲究的：它必须在 continue 【之后】。
            #      MT=301 的值是 9.12e9，但它是冗余道、根本不参与求和，
            #      放在 continue 之前会把一个无辜的道拦下来。
            #      —— 「assert 要挡在它要挡的那个操作前面」，这里那个操作是【求和】。
            assert at_i0[int(mt)] < 1e6, \
                "%s (MT=%d) 在热能点是 %.3e barn —— 这不可能是截面，" \
                "检查 redundant 标志" % (name, mt, at_i0[int(mt)])

            # ---- 求和：把这个道加到 total 的正确位置上 ----
            #   total[thr:] 有 len(E)-thr 格，len(xs) 也是 len(E)-thr，正好对齐。
            #   （写成 thr-1 会 broadcast 报错；thr=0 时 total[-1:] 更阴 ——
            #     负数下标是从末尾数的，那是最后一格。）
            total[thr:] += xs
            n_add += 1

    print("[%s] %d 个道，加了 %d 个，跳过 %d 个冗余道"
          % (nuc, len(names), n_add, len(names) - n_add))

    # ---- 判据 D：总截面必须处处为正 ----
    #   抓「下标错位把零填进了不该零的地方」「读到了负数」。
    #   np.all(条件) = 数组里每一个元素都满足条件吗 → True / False
    #   np.min(x)   = 最小值
    assert np.all(total > 0), "总截面出现非正值，最小 %.3e" % np.min(total)

    return E, total, at_i0, i0,awr


# =============================================================================
#  主程序
# =============================================================================
if __name__ == "__main__":

    E, total, at_i0, i0,awr = total_xs(NUC, T)

    print()
    print("能量网格 %d 点，热能点 i0 = %d，E[i0] = %.6e eV" % (len(E), i0, E[i0]))
    print("总截面 total[i0] = %.4f barn" % total[i0])
    print()
    print("参照物（第 1 步那张表里的数）：")
    print("   MT=107 (n,α) 总和   = %.4f barn   ← redundant=1，没参与求和" % at_i0[107])
    print("   MT=800 (n,α0)       = %.4f barn" % at_i0[800])
    print("   MT=801 (n,α1)       = %.4f barn" % at_i0[801])
    print("   MT=2   弹性         = %.4f barn" % at_i0[2])
    print("   MT=102 俘获         = %.4f barn" % at_i0[102])
    print()

    # =========================================================================
    #  ★ 判据 C：留给你填。这是今天最后一个要你动脑的地方。
    # =========================================================================
    #
    #  你已经推出来的事实：
    #     · total 应该比 MT=107 【大一点点】
    #     · 大出来的正是 MT=2 + MT=102 + 那三个小的 ≈ 2.6 barn
    #     · 也就是相对差约 0.00067（千分之 0.67）
    #
    #  这条判据要同时抓住两种错：
    #     ① 重复加了冗余道  → total/at_i0[107] 会变成 ≈ 2，不是 ≈ 1.0007
    #     ② 漏加了 800 或 801 → total/at_i0[107] 会掉到 0.94 或 0.06
    #
    #  🔴 所以它应该是一个【区间】判据，不是「大于」或「小于」。
    #     形状提示：   assert 下界 < total[i0] / at_i0[107] < 上界
    #
    #  ⚠️ 上下界怎么定？**由物理导出，不许拍脑袋。**
    #     这是 9/5「±5% 会让 A=1 必炸」和 9/9「容差必须由量级导出」的第三次应用。
    #     想一想：total 比 107 大出来的那部分，有没有可能突然变大很多？
    #
    assert 1.0<total[i0]/at_i0[107]<1.01, \
        "总截面 / MT107 = %.6f，超出预期区间" % (total[i0] / at_i0[107])
    print("判据C：total/MT107 = %.6f  ✅" % (total[i0] / at_i0[107]))

    # =========================================================================
    #  用 1/v 律把结果搬到 0.0253 eV —— 和 9/9 实测的 3844 对照
    # =========================================================================
    #  网格点 E[i0] = 0.024638 eV 不是 0.0253 eV。
    #  B-10 在热能区服从 1/v，即 sigma ∝ E^(-1/2)（白板题⑥ 实测 p = -0.500056）。
    #  所以：sigma(0.0253) = sigma(E[i0]) * sqrt(E[i0]/0.0253)
    #
    #  🔴 这一步不是为了好看。它是【两条独立的路走到同一个数】：
    #     一条是今天这张表 + 1/v 律，一条是你 9/9 在真实数据上量的 3844。
    sigma_at_0253 = at_i0[107] * np.sqrt(E[i0] / E_TEST)
    print()
    print("MT=107 在 E[i0]=%.6e eV 处      = %.2f barn" % (E[i0], at_i0[107]))
    print("用 1/v 搬到 %.4f eV              = %.2f barn" % (E_TEST, sigma_at_0253))
    print("9/9 实测值                        = 3844 barn")
    print("→ 相对差 %.3e" % abs(sigma_at_0253 / 3844.0 - 1.0))
    print()
    print("⚠️ 注意：这一步是【外推】，用的是 1/v 律这个物理假设，不是真插值。")
    print("   真正的插值在第 3 步做 —— 用白板题⑥ 的 log-log 公式，")
    print("   不假设任何物理规律，只用数据本身。两个结果应该几乎一样。")
