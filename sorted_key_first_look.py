# 要解决的问题：
#   排序后线性扫描，扫的是"排好序的"，可返回的必须是【原始下标】。
#   所以我们不排 sigma 本身，我们【把下标重新排个队】。
#
# 这是 2026-09-18 唯一一个新语法点。其余都是你会的。

sigma = [3.0, 0.0, 7.0, 1.0]
n = len(sigma)

print("sigma       =", sigma)
print("原始下标清单 =", list(range(n)))
print()

# ------------------------------------------------------------
# 写法甲：sorted(..., key=..., reverse=True)
# ------------------------------------------------------------
#
# sorted(一串东西, key=一个函数, reverse=True)
#   - 它把"一串东西"排个队，返回【一个新列表】，原来那串一个字不动
#   - key 是一个函数。排序时它会【拿这串东西里的每一个】去问这个函数：
#       "这一个，拿哪个数去比大小？"
#   - reverse=True 表示从大到小
#
# 这里"一串东西"是 range(n)，也就是 0,1,2,3 这些【下标】。
# 所以 key 收到的是一个下标 i，我们回答"拿 sigma[i] 去比"。
#
# lambda i: sigma[i]
#   这是【新东西】。它就是"一个临时的、没名字的函数"，等价于：
#       def 临时(i):
#           return sigma[i]
#   写成 lambda 只是不想为它单独起个名字。
#   读法：lambda 【参数】: 【返回值】

order = sorted(range(n), key=lambda i: sigma[i], reverse=True)

print("写法甲 order =", order)

# ------------------------------------------------------------
# 写法乙：不用 lambda，用你 9/15 已经过关的列表推导式
# ------------------------------------------------------------
#
# 先把 (截面, 下标) 配成对，排序默认先比第一个元素，
# 再把下标摘出来。两种写法结果完全一样。

pairs = sorted([(sigma[i], i) for i in range(n)], reverse=True)
order2 = [p[1] for p in pairs]

print("写法乙 order =", order2)
print("两种写法一致 :", order == order2)
print()

# ------------------------------------------------------------
# 怎么读 order
# ------------------------------------------------------------
print("order 的读法：")
for rank in range(n):
    k = order[rank]
    print("   第 %d 名  ->  原始下标 k = %d,  sigma[k] = %.1f" % (rank, k, sigma[k]))
print()

# ------------------------------------------------------------
# 🔴 最要紧的一句
# ------------------------------------------------------------
print("sigma 一个字没动 :", sigma)
print()
print("🔴 rank 是排名（0,1,2,...），k = order[rank] 是原始下标。")
print("   扫描要按 rank 走，返回的必须是 k。")
print("   零截面道（sigma=0）排完序全在【末尾】—— 记住这一点，填空 2 时要用。")
