import math
import os
import h5py
import numpy as np
from xs_lookup import LIB, load_nuclide
from lesson07_freegas import sigma_at_ext

E_TEST = [3.1e-6, 4.7e-4, 0.0246, 0.43]
E_REF  = 0.137
TOL    = 5e-4


def broaden_factor(y):
    """常数截面的自由气体展宽因子 σ̄/σ₀（讲义 §8 判据 4 那个闭式）。"""
    return (1.0 + 1.0 / (2.0 * y * y)) * math.erf(y) + math.exp(-y * y) / (y * math.sqrt(math.pi))


def read_direct(nuc):
    """路 1 用的数：直接用 h5py 读，不经过 load_nuclide。"""
    with h5py.File(os.path.join(LIB, nuc + ".h5"), "r") as f:
        root = f[nuc]
        E0 = root["energy"]["0K"][:]
        ds = root["reactions"]["reaction_002"]["0K"]["xs"]
        assert int(ds.attrs["threshold_idx"]) == 0, "弹性道不该有阈值"
        el0 = ds[:]
        kT = float(root["kTs"]["294K"][()])
        kT0 = float(root["kTs"]["0K"][()])
        awr = float(root.attrs["atomic_weight_ratio"])
    return E0, el0, kT, kT0, awr


if __name__ == "__main__":
    E0, el0, kT, kT0, awr = read_direct("H1")
    # 自由原子截面：0K 表在 E_REF 的值，再除掉 0.1 K 那一层展宽（约 3e-5）
    sig0 = np.interp(E_REF, E0, el0) / broaden_factor(math.sqrt(E_REF * awr / kT0))
    print("路 1：awr = %.6f   kT(294K) = %.6f eV   kT(0K) = %.4g eV   σ₀ = %.5f b（取自 0K 表 %.3g eV）"
          % (awr, kT, kT0, sig0, E_REF))

    E, mts, XS, _ = load_nuclide("H1", "294K")
    i2 = mts.index(2)

    print("%-10s %-8s %-14s %-14s %s" % ("E (eV)", "y", "路1 闭式 (b)", "路2 代码 (b)", "相对差"))
    worst = 0.0
    for e in E_TEST:
        y = math.sqrt(e * awr / kT)
        pred = sig0 * broaden_factor(y)
        sig, total = sigma_at_ext(E, XS, e)
        got = sig[i2]
        rel = got / pred - 1.0
        worst = max(worst, abs(rel))
        print("%-10.3g %-8.4f %-14.5f %-14.5f %+.2e" % (e, y, pred, got, rel))
        assert abs(rel) < TOL, \
            "判据4：E=%.3g eV 处弹性截面 代码 %.5f b ≠ 闭式 %.5f b，相对差 %+.2e 超过 %.0e" \
            % (e, got, pred, rel, TOL)

    # 只打印、不判：把「悬着的 1%」那个点的账摆出来
    e = E[242]
    sig, total = sigma_at_ext(E, XS, e)
    print("\nE = %.7g eV（网格第 242 点）：弹性 %.5f + 俘获 %.5f = 总 %.5f b"
          % (e, sig[i2], total - sig[i2], total))
    print("判据 4 全过（最大相对差 %.2e，阈值 %.0e）" % (worst, TOL))
