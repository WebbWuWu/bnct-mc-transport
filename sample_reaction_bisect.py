#
# 【它的定位：慢，但对】
#   9/16 实测（n=48，2 万次）：
#       二分（每次现算 s）   平均读表 274.8 次   最坏 480
#       线性扫描             平均读表  24.9 次   最坏  48
#       排序后线性扫描       平均读表   1.1 次   最坏   3
#   也就是说这一版比排序后线性扫描【慢约 250 倍】。
#
#   🔴 但它不是拿来跑的，是拿来【对拍】的：
#      「判据的两边必须来自两条独立的路」（9/7 立，9/17 恒真 assert 第六次重申）。
#      主力实现（排序后线性扫描）和这一版是两条独立的路，
#      两条路算出同一个 k，才是一条有分辨率的判据。
#      所以【这个文件永远不进热路径，也永远不要为了快去改它】。
#
# 【为什么它这么慢】
#   s(k) 不是一张表，是一个每次调用都要现场累加 k 次的【函数】。
#   9/16 的结论：「算法复杂度」这个词只在你数清楚每一步实际花了什么之后才有意义。
#   你以为在查表，其实在算 48 遍加法。
#   —— 这个「慢」是故意保留的，它是那条教训的物证。
#
# 【接口约定】
#   sample_reaction_bisect(sigma, total, xi) -> k
#
#   sigma : 各反应道的截面，list 或 array，允许含 0（阈值反应在热能点就是 0）
#   total : 总截面。【它是从外面传进来的】，理由见下面「关于 total」
#   xi    : 一个 [0,1) 的随机数。【随机性由调用方负责】
#   返回  : 原始下标 k，满足 s(k) <= xi < s(k+1)
#
#   🔴 函数里没有 rng，也没有 n。
#      - 没有 rng：9/16 立的纪律。函数只做「xi -> k」这个确定的映射，
#        「xi 从哪来」是调用方的事。好处一是可测（能写确定性判据），
#        好处二是第 13 课每线程有自己的 rng 状态，到时一行不用改。
#      - 没有 n：9/16 Claude 的锅。n 从外面来 = 函数签名说了谎
#        （三个参数声称「我需要的全在这三个里」，却偷偷用了第四个）。
#        长度由数组自己说，别让别人替它记。
#
# 【关于 total：一次有意识的交易】
#   total 完全可以由 sum(sigma) 现算，留着它只有一个理由：省那次求和
#   （第 13 课每秒上亿次碰撞，这是真钱）。
#   代价是「sigma 和 total 可能对不上，而且不报错」。
#   🔴 交易可以做，但必须写下收据 —— 下面那条 assert 就是收据。
#   （9/16：一个能从其它参数算出来的参数，就是一个对不上的机会。）
#
# ============================================================


def sample_reaction_bisect(sigma, total, xi):
    """按 sigma[k]/total 的占比抽一个反应道，返回原始下标 k。

    不变量：循环中始终维持   s(low) <= xi < s(hi)
    其中 s(k) = (sigma[0] + ... + sigma[k-1]) / total，即前 k 项的累积占比。
    注意 s(0) = 0，s(n) = 1 —— n 个区间，n+1 个分界点（9/16「栅栏桩」）。
    """

    n = len(sigma)                      # 修改 2：n 不从外面来，数组自己知道自己多长

    # ---- 判据 1 ------------------------------------------------
    # 挡住 total <= 0，顺带挡住 total = nan（nan > 0 为 False）。
    assert total > 0, "total 必须为正，实际是 %r" % total

    # ---- 判据 2 ------------------------------------------------
    # 收据：sigma 和 total 必须对得上。相对容差（9/9：量级在变的东西，容差要用相对的）。
    assert abs(sum(sigma) / total - 1) < 1e-12, \
        "sigma 与 total 对不上：sum(sigma)=%.17g  total=%.17g  比值=%.17g" \
        % (sum(sigma), total, sum(sigma) / total)

    # ---- 判据 3 ------------------------------------------------
    # 范围判据【免费附赠一个 NaN 判据】—— nan 过不了任何一个比较（9/16）。
    # 开闭方向必须和下面的 <= / < 对齐：random() 返回 [0,1)，左闭右开（9/6 已核对）。
    assert 0 <= xi < 1, "xi 越界或是 nan: %r" % xi

    def s(k):
        """前 k 项的累积占比。s(0)=0，s(n)=1。
        🔴 每次调用现场累加 k 次 —— 这一版慢在这里，故意不优化。"""
        acc = 0.0
        for i in range(k):
            acc += sigma[i]
        return acc / total

    low = 0
    hi = n                              # 修改 6：栅栏桩。hi 初值必须是 n，不是 n-1。
                                        # 写 n-1 的话开局不变量 xi < s(n-1) 本身就不成立，
                                        # 而「结构上不可能返回零截面道」那个保护就建立在
                                        # 一个不成立的前提上 —— 等于没有。
                                        # 后果：最后一道永远抽不到，且不报错。

    steps = 0                           # 修改 7：保险丝的两半，缺一根就是恒真 assert
                                        # （9/9：只补 steps=0 而漏掉 steps+=1，
                                        #  程序照跑、判据全过，而那根保险丝已经断了）

    while hi - low > 1:                 # 修改 5：方向。写成 hi-low == 1 会死循环。
        h = (low + hi) // 2             # 修改 4：h 必须写在【循环体内】，跟着区间走。
                                        # 挪到循环外 = 死循环，且不报错（9/7 第四次，反向形态）
        if s(h) <= xi:                  # 修改 8：比较符号与区间开闭方向对齐。
            low = h                     # s(low) <= xi 这一半仍然成立
        else:
            hi = h                      # xi < s(hi) 这一半仍然成立
        steps += 1

        # ---- 判据 4 --------------------------------------------
        # 🔴 这是【你 9/16 设计的判据，原值照搬】：n=48 时 hi-low 每轮至少减半，
        #    48->24->12->6->3->2->1，最多 6 轮，所以写 8。
        #    ⚠️ 留一个问题给你，我没有替你决定：
        #       9/17 你自己立了「一个跟任何参数都没关系的常数，通常是拍的」。
        #       8 是跟着 n=48 来的，不是跟着任何参数来的。
        #       换个核素 n 变了怎么办？要不要改成跟 len(sigma) 走？
        #       —— 这是判据，判据是你的，我不动。
        assert steps <= 8, "二分没有收敛，steps=%d  low=%d  hi=%d  xi=%.17g" \
            % (steps, low, hi, xi)

    # 收敛时 hi == low + 1，即 s(low) <= xi < s(low+1)。
    #
    # 🔴 结构上不可能返回零截面道：
    #    sigma[low] == 0  ==>  s(low) == s(low+1)
    #    ==>  s(low) <= xi < s(low) 不可能同时成立
    #    所以根本不需要额外写 assert sigma[low] > 0 来防它。
    #    （9/9「else 的真正好处是把互补从『你手写对了』变成『结构上不可能写错』」的第二次。
    #     ⚠️ 排序后线性扫描版【没有】这个保护，只能靠把 < 写对 —— 这是两版的一处真差别。）
    return low


