if __name__ == "__main__":

    # --- 自测 1：确定性。xi=0 必须落在第一个非零道上 ---
    sig = [3.0, 0.0, 7.0]
    tot = 10.0
    assert sample_reaction_bisect(sig, tot, 0.0) == 0
    assert sample_reaction_bisect(sig, tot, 0.29999) == 0
    assert sample_reaction_bisect(sig, tot, 0.3) == 2      # 0.3 是 s(1)=s(2) 的位置
    assert sample_reaction_bisect(sig, tot, 0.99999) == 2
    print("自测 1 确定性：过")

    # --- 自测 2：零截面道一次都不返回 ---
    hit = set()
    for i in range(10000):
        hit.add(sample_reaction_bisect(sig, tot, i / 10000.0))
    assert 1 not in hit, "返回了零截面道"
    assert hit == {0, 2}
    print("自测 2 零截面道：过，返回值集合 =", sorted(hit))

    # --- 自测 3：保险丝要亲眼看它响一次 ---
    #     （9/9：没见过它响，不算装上了）
    #     手法：给一个 600 道的 sigma，让 8 轮不够用，逼 steps 超 8。
    #
    # 🔴 2026-09-18 跑这一条时当场撞到一件事，留给你判断，我没有动：
    #    它响了，消息是「二分没有收敛，steps=9  low=300  hi=301」。
    #    可是 hi - low == 1 —— 它【已经收敛了】。
    #    真因不是没收敛，是 600 个道需要 10 轮，而这条判据的上界 8 是照
    #    n=48 定的。
    #    ==> 这是 9/9 记的「判据响了，但指向错误的原因」（形态 2），活的。
    #    ==> 它同时是上面那个问题的答案的一半：8 该不该跟着 len(sigma) 走。
    #    判据是你的，我只把现象摆在这里。
    big = [1.0] * 600
    try:
        sample_reaction_bisect(big, 600.0, 0.5)
    except AssertionError as e:
        print("自测 3 保险丝：响了 ->", e)
    else:
        raise SystemExit("自测 3 失败：保险丝没响，它可能是断的")

    # --- 自测 4：三条入口判据各手动触发一次，看消息长什么样 ---
    #     （9/9：assert 的消息必须至少手动触发一次）
    for bad in [(sig, 0.0, 0.5), (sig, 11.0, 0.5), (sig, tot, float("nan"))]:
        try:
            sample_reaction_bisect(*bad)
        except AssertionError as e:
            print("自测 4 入口判据：响了 ->", e)
        else:
            raise SystemExit("自测 4 失败：入口判据没响")
