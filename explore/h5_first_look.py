#
#  🔴 强烈建议的跑法（今天顺带练调试器）：
#     在第一行 `with` 那里点一个断点（行号左边点一下，出现红点），按 F5，
#     然后一直按 F10 单步走，**每走一行就去看左边"变量"面板里 root、rxs、one
#     这些东西长什么样**。你 9/7 学的调试器，今天是第一次用在"看数据结构"上，
#     而不是"抓 bug"上 —— 这是它第二个、也是更常用的用途。
