import h5py

PATH = r"E:\BNCT_GPU\lib80x_hdf5\B10.h5"

with h5py.File(PATH, "r") as f:

    # =========================================================================
    #  第 1 层：文件 f  —— 它像一个最外层的抽屉
    # =========================================================================
    # type(某东西) 告诉你"这是个什么类型的东西"。
    # 今天你只需要认三种类型名：File、Group、Dataset。
    print("【第1层】f 的类型：", type(f))
    print("         f 里面有：", list(f.keys()))
    print()

    # =========================================================================
    #  第 2 层：root = f["B10"]  —— 中括号，按名字取出一个子项
    # =========================================================================
    root = f["B10"]
    print("【第2层】root = f[\"B10\"]")
    print("         类型：", type(root))          # ← Group
    print("         里面有：", list(root.keys()))  # ← ['energy', 'kTs', 'reactions']
    print()
    #  ⚠️ 对比一下这两行，它们是【两条独立的路】：
    print("         root 的子项(走中括号)：", list(root.keys()))
    print("         root 的属性(走 .attrs)：", list(root.attrs.keys()))
    print("         → 两个列表内容完全不同。这就是「便利贴不在抽屉目录里」。")
    print()

    # =========================================================================
    #  第 3 层：rxs = root["reactions"]  —— 再往下一层
    # =========================================================================
    rxs = root["reactions"]
    print("【第3层】rxs = root[\"reactions\"]")
    print("         类型：", type(rxs))           # ← 还是 Group

    # 🔴 这一行就是脚手架里 ① 的答案形状：
    #       list( 某个group .keys())
    #    把「某个group」换成 rxs（或者直接换成 root["reactions"]），就是这一行。
    names = list(rxs.keys())
    print("         一共 %d 个反应道" % len(names))
    print("         前 5 个：", names[:5])        # [:5] = 取前 5 个，看一眼就够
    print()

    # =========================================================================
    #  第 4 层：一个具体的反应道 —— attrs 第一次真正登场
    # =========================================================================
    # names[0] 是列表里的第一个名字。用它而不是硬写 "reaction_002"，
    # 是为了这个文件换成 H1.h5 也照样能跑。
    name = names[0]
    one  = rxs[name]

    print("【第4层】one = rxs[\"%s\"]" % name)
    print("         类型：", type(one))           # ← 还是 Group
    print()
    print("         ▼ 两条路，看清楚区别 ▼")
    print("         子项  one.keys()  ：", list(one.keys()))
    print("         属性  one.attrs.keys()：", list(one.attrs.keys()))
    print()
    print("         → 上面一行是【抽屉里装的东西】，下面一行是【贴在抽屉上的便利贴】。")
    print("         → 便利贴的名字里应该有 mt 和 redundant。如果没有，停下来告诉我。")
    print()

    # 🔴 这两行就是脚手架里 ② 的答案形状：
    print("         one.attrs[\"mt\"]        =", one.attrs["mt"])
    print("         one.attrs[\"redundant\"] =", one.attrs["redundant"])
    print()
    print("         ⚠️ 注意 .attrs 【不加引号】。写成 one[\".attrs\"] 是在找一个")
    print("            名字叫 .attrs 的子项 —— 它不存在，因为 .attrs 不是钥匙，是动作。")
    print()

    # 多看几个道的属性，确认每个道都有这两张便利贴
    print("         前 5 个道的 mt / redundant：")
    for n in names[:5]:
        g = rxs[n]
        print("           %-16s mt=%-4d redundant=%d"
              % (n, g.attrs["mt"], g.attrs["redundant"]))
    print()

    # =========================================================================
    #  第 5 层：dataset —— 第一次遇到"不是 Group"的东西
    # =========================================================================
    xs_ds = one["294K"]["xs"]

    print("【第5层】xs_ds = one[\"294K\"][\"xs\"]")
    print("         类型：", type(xs_ds))         # ← Dataset！不是 Group 了
    print("         形状 xs_ds.shape ：", xs_ds.shape)   # .shape 是【部件】，不加括号
    print("         属性 xs_ds.attrs ：", list(xs_ds.attrs.keys()))
    print("         threshold_idx =", xs_ds.attrs["threshold_idx"])
    print()
    print("         ⚠️ threshold_idx 贴在【这个 dataset】上，不是贴在反应道上。")
    print("            所以走 xs_ds.attrs，不是 one.attrs。—— 这是 ③ 的第二行。")
    print()

    # =========================================================================
    #  第 6 层：[:]  —— 从"句柄"变成"真数据"
    # =========================================================================
    arr = xs_ds[:]
    print("【第6层】arr = xs_ds[:]")
    print("         xs_ds 的类型：", type(xs_ds))  # ← Dataset（数据还在磁盘上）
    print("         arr   的类型：", type(arr))    # ← numpy.ndarray（数据在内存里了）
    print("         arr 有 %d 个数，前 3 个：%s" % (len(arr), arr[:3]))
    print()
    print("         🔴 对比这两行，今天最该记住的一条顺序：")
    print("            xs_ds.attrs  → 有属性，能取")
    try:
        arr.attrs
    except AttributeError as e:
        print("            arr.attrs    → 报错：%s" % e)
    print("            → [:] 一取，便利贴就丢了。**所以 .attrs 必须在 [:] 之前取。**")
    print()

    # =========================================================================
    #  收尾：三种类型，三种动作
    # =========================================================================
    print("=" * 70)
    print("三种类型：")
    print("   File     整个文件")
    print("   Group    抽屉，里面还能装抽屉和数据集。用 .keys() 看里面有什么")
    print("   Dataset  一叠纸，里面是数组。用 [:] 读进内存")
    print()
    print("三种动作：")
    print("   东西[钥匙]     中括号 = 从里面按钥匙取子项    钥匙是名字时【要加引号】")
    print("   东西.部件      点号   = 自带的部件            【不加引号，不加括号】")
    print("                         例：.attrs  .shape")
    print("   东西.动作()    点号+括号 = 让它做一件事       【不加引号，必须加括号】")
    print("                         例：.keys()")
    print("=" * 70)
