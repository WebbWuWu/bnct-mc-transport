import numpy as np

NL = 30                          # 层数
M = 200000                       # 模拟次数
RHO = 0.4                        # 真实的层间相关 ρ
RHO_BAR = 0.4                    # 判据里用的 ρ̄
Z_T_MAX = 3.0                    # 总量门槛
Q_LO, Q_HI = 13.12, 52.34        # χ²₂₉ 的 0.5% 和 99.5% 分位
SEED = 20261105


def alarm_rate(delta, rng):
    """delta：长度 30 的已知偏差（单位：SE）。返回（总量报警比例，形状报警比例，任一报警比例）。"""
    g0 = rng.standard_normal((M, 1))                       # 每次模拟 1 个公共数（30 层共用）
    g = rng.standard_normal((M, NL))                       # 每次模拟 30 个各层自己的数
    z = np.sqrt(RHO) * g0 + np.sqrt(1.0 - RHO) * g + delta  # 第 1 步 + 第 5 步
    z_T = z.sum(axis=1) / np.sqrt(NL + NL * (NL - 1) * RHO)  # 第 2 步
    zbar = z.mean(axis=1, keepdims=True)
    Q = ((z - zbar) ** 2).sum(axis=1) / (1.0 - RHO_BAR)    # 第 3 步
    bad_T = np.abs(z_T) > Z_T_MAX                           # 第 4 步
    bad_Q = (Q < Q_LO) | (Q > Q_HI)
    return bad_T.mean(), bad_Q.mean(), (bad_T | bad_Q).mean()


if __name__ == "__main__":
    rng = np.random.default_rng(SEED)
    cases = [("① 两边都对（只有涨落）", np.zeros(NL)),
             ("② 形状歪：一头 −1.3、另一头 +1.3", np.linspace(-1.3, 1.3, NL)),
             ("③ 整体偏 +1.3", np.full(NL, 1.3))]
    print("ρ = %.2f · ρ̄ = %.2f · %d 层 · 每种情况模拟 %d 次\n" % (RHO, RHO_BAR, NL, M))
    print("%-30s %10s %10s %10s" % ("情况", "总量报警", "形状报警", "任一报警"))
    for name, delta in cases:
        t, q, a = alarm_rate(delta, rng)
        print("%-30s %9.2f%% %9.2f%% %9.2f%%" % (name, 100 * t, 100 * q, 100 * a))

