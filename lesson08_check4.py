#
#  记号
#    「每源中子」   除以源中子数 N 之后的量
#    吸收权重       隐式俘获下，每次碰撞被「打折」掉的那部分权重  wt × Σ_a/Σ_t
#    批（batch）    同一个问题用 K 个不同种子各跑 n 条历史；每批算出一个数，
#                   K 个数的离散程度就给出误差棒：SE = 批间标准差 / √K
#                   （run_slab 只返回总和，没有「每条历史」的总吸收，所以用批来估误差）
#    t              偏离几个 SE = 平均差 / SE（K 小时它服从 t 分布，不是正态）
#
#  ------------------------------------------------------------
#  4a  粒子账（隐式俘获 + 轮盘赌）
#  ------------------------------------------------------------
#    一个源中子带着权重 1 进来，最后权重只有三个去处：从两侧漏出、在碰撞时被打折吸收、
#    被轮盘赌杀掉（赌赢提权又加回来，期望净值为 0 —— 白板题 ⑪）。所以
#        1 = 漏出权重 + 吸收权重 + 轮盘赌净值          （期望意义下）
#    路 A（漏出那头）：  吸收 = 1 − (nt_w + nr_w) / n
#    路 B（径迹长度）：  吸收 = Σ_层 [ (n,γ) 反应率 + 硼 (n,α) 反应率 + 氮 (n,p) 反应率 ] / n
#                        = Σ_层 [ ag + Bc / Q_val + Nc / Q_600 ] / n
#        （假库里吸收道只有这四种：全部 MT=102、B-10 的 800/801、N-14 的 600，所以 B 是完整的吸收率）
#    两条路记账的地方完全不同：A 在出边界那一行，B 在拆层循环里每一段。
#    🔴 和讲义 §8 的差别：讲义写的是「打折掉的权重之和 vs 径迹长度」。run_slab 没有返回打折之和，
#       而「1 − 漏出」= 打折之和 + 轮盘赌净值，期望相同，不用再改 run_slab。
#    判：K = 20 批的平均差 |t| < 4。
#    抓：打折用的 Σ_t 和打分用的截面不一致（一处含 ¹⁰B、一处漏了）；赢了提到 wt_lo；
#        漏出权重记错（加了方向余弦 w、或没加）；某个吸收分量的系数漏核素或乘错 Q。
#    不抓：两条路共用的东西 —— 截面查表、wt 本身。
#
#  ------------------------------------------------------------
#  4b  能量账（纯散射，t_cut 截断，一条都漏不出去）
#  ------------------------------------------------------------
#    只有散射时，中子丢掉的动能全部交给反冲核：每条历史
#        E_src − E(t_cut 时刻) = Σ_这条历史的碰撞 (E − E')
#    把 N 条加起来：
#    路 A（首尾）：  N × E_src − Σ E_cut
#    路 B（逐次）：  Σ_层 DH_sum
#    这是恒等式，不是统计判据：两边只差舍入误差。
#    容差的来历：一共约 N × 40 = 8 万次加法，每次相对舍入约 1e-16 →
#        累积约 1e-11（相对）；再乘 100 倍余量 → 1e-9。
#    抓：负值截成 0（上散射被扔掉 —— 框架第 5 问「负值照记」）、符号写反、
#        E − E' 在运动学之前算（恒为 0）、某种碰撞分支没记 D_H。
#    不抓：D_H 用打折前还是打折后的 wt（纯散射时打折因子 = 1）—— 靠讲义自测第 5 题的推导保证。
#
#  10/10 容器里在故意改坏的实现上试过（结果见文件末尾的表）。
