import math
import numpy as np
from lesson07_freegas import run_slab, table_1overE, Q_val

# ------------------------------------------------------------
#  假库：截面量级同真库软组织（散射取常数，吸收取 1/v），能量格点 400 个、对数等距
#  （xs_lookup 是线性插值，1/v 曲线要格点够密：相邻格点能量比 1.055，插值误差约 1e-4）
# ------------------------------------------------------------
KT = 8.617333262e-5 * 293.6          # eV，294K 那一项的 kT
EG = np.logspace(-5, math.log10(2.0e4), 400)
M_N, N_A, RHO = 1.00866491588, 6.02214076e23, 1.06
Q_600 = 625876.1                     # N-14 (n,p)，eV（10/9 核数）


def v1(s0):
    """1/v 截面：0.0253 eV 处为 s0 barn"""
    return s0 * np.sqrt(0.0253 / EG)


def const(s):
    return np.full(len(EG), s)


def fake_tissue():
    """五核素假组织（质量份额同 ICRU-44 + 15 ppm ¹⁰B）。返回 (nuclides, order)。"""
    spec = {   # 名字: (质量份额, awr, mts, XS, Q_value)
        "H1":  (0.102, 0.999167, [2, 102], [const(20.47), v1(0.3326)], [0.0, 2224631.0]),
        "C12": (0.143, 11.896914, [2, 102], [const(4.74), v1(0.00353)], [0.0, 4946310.0]),
        "N14": (0.034, 13.882956, [2, 102, 600], [const(10.05), v1(0.0796), v1(1.82722)],
                [0.0, 10833390.0, Q_600]),
        "O16": (0.708, 15.857510, [2, 102], [const(3.852), v1(1.9e-4)], [0.0, 4143080.0]),
        "B10": (15e-6, 9.926921, [2, 102, 800, 801],
                [const(2.19383), v1(0.5), v1(3844 * 0.062984), v1(3844 * 0.937016)],
                [0.0, 11454000.0, 2789323.0, 2311472.0]),
    }
    nucs, order = [], []
    i0 = int(np.searchsorted(EG, 0.0253)) - 1
    for name, (w, awr, mts, XS, Q) in spec.items():
        dens = w * RHO * N_A / (awr * M_N)
        nucs.append({"name": name, "E": EG, "mts": mts, "XS": XS, "Q_value": Q,
                     "awr": awr, "dens": dens, "kT": KT})
        order.append(sorted(range(len(mts)), key=lambda t: XS[t][i0], reverse=True))
    return nucs, order


def fake_scatter():
    """纯散射假料：只有 H、O 两种核素，只有散射（量级同组织）。
    MT=102 那一道截面全 0：run_slab 开头对每个核素都要 .index(102)（10/9 第 12 条同一件事）。"""
    zero = np.zeros(len(EG))
    nucs = [
        {"name": "H1", "E": EG, "mts": [2, 102], "XS": [const(20.47), zero], "Q_value": [0.0, 0.0],
         "awr": 0.999167, "dens": 6.46e22, "kT": KT},
        {"name": "O16", "E": EG, "mts": [2, 102], "XS": [const(3.852), zero], "Q_value": [0.0, 0.0],
         "awr": 15.857510, "dens": 2.83e22, "kT": KT},
    ]
    return nucs, [[0, 1], [0, 1]]


# ============================================================
#  4a 粒子账
# ============================================================
def check4a(K=20, n=1000):
    nucs, order = fake_tissue()
    edges = [0.5, 1.0, 3.0, 10.0, 50.0, 200.0, 1000.0, 3000.0, 10000.0]
    src = (edges, table_1overE(edges))
    print("判据 4a  粒子账（假库组织 + 15 ppm，1/E 源，d = 15 cm，NL = 30，隐式；%d 批 × %d 条）" % (K, n))
    A, B, D = [], [], []
    n_ki = 0
    for b in range(K):
        r = run_slab(n, 41017 + 7 * b, 15.0, nucs, None, order, z_src=0.0,
                     implicit=True, NL=30, src=src)
        # [Claude assert] 抓：有历史撞满 Max 没结束 —— 它手里的权重既没漏出也没被吸收，账本身就不平
        assert r["n_sd"] == 0, "第 %d 批有 %d 条历史撞满 Max，粒子账无法成立" % (b, r["n_sd"])
        a = 1.0 - (r["nt_w"] + r["nr_w"]) / n
        bb = (sum(r["ag_sum"]) + sum(r["Bc_sum"]) / Q_val + sum(r["Nc_sum"]) / Q_600) / n
        A.append(a); B.append(bb); D.append(a - bb)
        n_ki += r["n_ki"]
    mA, mB, mD = sum(A) / K, sum(B) / K, sum(D) / K
    sD = math.sqrt(sum((x - mD) ** 2 for x in D) / (K - 1))
    se = sD / math.sqrt(K)
    t = mD / se
    print("   路 A  1 − 漏出权重      = %.5f / 源中子" % mA)
    print("   路 B  径迹长度吸收率    = %.5f / 源中子" % mB)
    print("   差 A − B = %+.2e ± %.1e（%d 批），t = %+.2f；轮盘赌共杀 %d 条" % (mD, se, K, t, n_ki))
    # [Claude assert] 抓：两条路对吸收的记账不一致（打折截面 vs 打分截面、提权、漏出权重、某个分量的系数）
    #   4 的来历：K−1 = 19 自由度的 t 分布，|t| > 4 的概率约 0.08%（全对时几乎不误报）
    assert abs(t) < 4.0, \
        "判据4a 粒子账不平：路 A（1−漏出）%.5f vs 路 B（径迹长度吸收）%.5f，差 %+.2e = %.1f SE" \
        % (mA, mB, mD, t)
    print("   |t| < 4  ✓")


# ============================================================
#  4b 能量账
# ============================================================
def check4b(N=2000):
    nucs, order = fake_scatter()
    E_SRC, D, T_CUT = 37.3, 80.0, 150.0
    r = run_slab(N, 52309, D, nucs, E_SRC, order, z_src=D / 2, t_cut=T_CUT,
                 implicit=True, NL=30)
    print("判据 4b  能量账（纯散射 H + O，单能 %.1f eV，板中心出发，t_cut = %.0f，N = %d）" % (E_SRC, T_CUT, N))
    # [Claude assert] 抓：有历史在 t_cut 之前就漏出 / 被杀 —— 那它带走的动能不在 E_cut 里，恒等式不成立
    assert r["nt_cut"] == N, \
        "只有 %d / %d 条历史活到 t_cut（漏出 %.4f+%.4f、轮盘赌 %d）：纯散射不该打折，板也够厚" \
        % (r["nt_cut"], N, r["frac_T"], r["frac_R"], r["n_ki"])
    path_a = N * E_SRC - sum(r["E_cut"])
    path_b = sum(r["DH_sum"])
    rel = abs(path_a - path_b) / (N * E_SRC)
    print("   路 A  N·E_src − Σ E_cut = %.9e eV" % path_a)
    print("   路 B  Σ DH_sum          = %.9e eV" % path_b)
    print("   相对差 %.1e（容差 1e-9）；t_cut 时平均能量 %.4f eV = %.3f kT"
          % (rel, sum(r["E_cut"]) / N, sum(r["E_cut"]) / N / KT))
    # [Claude assert] 抓：D_H 截成 0 / 符号反 / 算在运动学之前 / 漏记某个分支 —— 都远大于 1e-9
    assert rel < 1e-9, \
        "判据4b 能量账不平：首尾算的沉积 %.9e eV vs 逐次碰撞记的 D_H %.9e eV，相对差 %.2e" \
        % (path_a, path_b, rel)
    print("   相对差 < 1e-9  ✓")


if __name__ == "__main__":
    check4b()
    print()
    check4a()
    print()
